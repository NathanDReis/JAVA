package com.nathan.cursojava.aula11;

public class VariaveisInteiras {

	public static void main(String[] args) {
		
		byte byteIdade = 20;
		short shortIdade = 21;
		int intIdade = 22;
		long longIdade = 23;
		
		System.out.println("Valor da variável byteIdade: " + byteIdade);	
		System.out.println("Valor da variável shortIdade: " + shortIdade);
		System.out.println("Valor da variável intIdade: " + intIdade);
		System.out.println("Valor da variável longIdade: " + longIdade);
		
	}

}
