package com.nathan.cursojava.aula11;

public class VariaveisFlutuante {

	public static void main(String[] args) {
		
		float floatPassagem = 2.90f;
		double doublePassagem = 2.90;

		System.out.println("Valor da passagem float: " + floatPassagem);
		System.out.println("Valor da passagem double: " + doublePassagem);
		
	}

}
